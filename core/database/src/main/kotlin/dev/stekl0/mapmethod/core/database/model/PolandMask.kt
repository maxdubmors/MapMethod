package dev.stekl0.mapmethod.core.database.model

/**
 * Hand-tuned boolean mask of Poland over its bounding box, 30 columns (west to east)
 * by 30 rows (north to south). Approximate borders for v1; refined later.
 */
internal object PolandMask {
    val rows: List<String> =
        listOf(
            "............111...............",
            "..........111111..............",
            "......1111111111111111111.....",
            ".......11111111111111111111...",
            "11111111111111..11111111111111",
            "11111111111111111111111111111.",
            ".11111111111111111111111111...",
            ".1111111111111111111111111111.",
            ".1111111111111111111111111111.",
            ".1111111111111111111111111111.",
            ".1111111111111111111111111111.",
            "..111111111111111111111111111.",
            "..111111111111111111111111111.",
            "..1111111111111111111111111111",
            "..1111111111111111111111111111",
            "..111111111111111111111111111.",
            "..111111111111111111111111111.",
            "..111111111111111111111111111.",
            "..111111111111111111111111111.",
            "..111111111111111111111111111.",
            "..111111111111111111111111111.",
            "...11111111111111111111111111.",
            "...1111111111111111111111111..",
            "....1111111111111111111111....",
            "........11111111111111111.....",
            ".............11111111111......",
            "..............111111111.......",
            "...................111111.....",
            "........................11....",
            "........................11....",
        )

    /** Cells in fill order: row by row north to south, west to east. */
    fun entities(): List<CellEntity> {
        val entities = mutableListOf<CellEntity>()
        var order = 0
        rows.forEachIndexed { row, line ->
            line.forEachIndexed { col, mark ->
                if (mark == '1') {
                    entities.add(CellEntity(orderIndex = order++, row = row, col = col, filledAt = null))
                }
            }
        }
        return entities
    }
}
